"""Write the synthetic demo dataset as plain SQL (`psql -f seed_demo.sql`). No Python DB driver needed."""
from __future__ import annotations

import json
from datetime import date
from typing import Iterable, Optional

from app.engine.config import StateConfig
from app.repository.dataset import Dataset, PolyUnit
from app.repository.memory import MemoryRepository

BATCH = 400


def q(v) -> str:
    if v is None:
        return "NULL"
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return repr(float(v)) if isinstance(v, float) else str(v)
    if isinstance(v, date):
        return f"'{v.isoformat()}'"
    return "'" + str(v).replace("'", "''") + "'"


def pt(lon: float, lat: float) -> str:
    return f"ST_SetSRID(ST_MakePoint({lon:.6f},{lat:.6f}),4326)"


def env(b) -> str:
    return f"ST_MakeEnvelope({b[0]:.6f},{b[1]:.6f},{b[2]:.6f},{b[3]:.6f},4326)"


def _insert(table: str, cols: str, rows: Iterable[str]) -> Iterable[str]:
    rows = list(rows)
    for i in range(0, len(rows), BATCH):
        chunk = rows[i:i + BATCH]
        yield f"INSERT INTO {table} ({cols}) VALUES\n" + ",\n".join(chunk) + ";"


def _setval(table: str, col: str) -> str:
    return f"SELECT setval(pg_get_serial_sequence('{table}','{col}'), (SELECT COALESCE(MAX({col}),1) FROM {table}));"


def _units(units: list[PolyUnit]) -> list[tuple]:
    out = []
    for u in units:
        xs = {round(p[0], 9) for p in u.ring}
        ys = {round(p[1], 9) for p in u.ring}
        assert len(xs) == 2 and len(ys) == 2, "demo units must be axis-aligned squares"
        out.append((u, u.bbox))
    return out


def export_seed_sql(ds: Dataset, cfg: StateConfig, today: Optional[date] = None) -> str:
    assert ds.is_demo, "refusing to export non-demo data through the demo exporter"
    today = today or date.today()
    repo = MemoryRepository(ds, cfg)
    L: list[str] = []
    a = L.append
    a("-- =====================================================================================")
    a("-- SYNTHETIC DEMONSTRATION DATA - NOT REAL. Generated by backend/demo/export_sql.py")
    a("-- Every row has is_demo = true. The API in APP_DATA_MODE=production never reads these rows.")
    a("-- =====================================================================================")
    a("BEGIN;")

    x0, y0, x1, y1 = ds.coverage_bbox
    a(f"INSERT INTO states (state_code,name_en,name_te,coverage_status,coverage_geom,config_key) VALUES "
      f"({q(ds.state_code)},{q(ds.state_en)},{q(ds.state_te)},'demo',ST_Multi({env(ds.coverage_bbox)}),'telangana') "
      f"ON CONFLICT (state_code) DO UPDATE SET coverage_status='demo', coverage_geom=EXCLUDED.coverage_geom;")

    for s in _insert("data_sources",
                     "source_id,name_en,name_te,publisher,layer_kind,url,license,version,retrieved_on,data_last_updated,is_demo,notes",
                     (f"({q(s.source_id)},{q(s.name_en)},{q(s.name_te)},{q(s.publisher)},{q(s.layer_kind)},{q(s.url)},"
                      f"{q(s.license)},NULL,{q(s.retrieved_on)},{q(s.data_last_updated)},true,{q(s.notes)})"
                      for s in ds.sources.values())):
        a(s)

    for s in _insert("admin_areas", "area_id,state_code,level,parent_id,name_en,name_te,centroid,gw_category,source_id,is_demo",
                     (f"({p.place_id},{q(ds.state_code)},{q(p.level)},{q(p.parent_id)},{q(p.name_en)},{q(p.name_te)},"
                      f"{pt(p.lon, p.lat)},NULL,{q(p.source_id)},true)" for p in ds.places)):
        a(s)
    a(_setval("admin_areas", "area_id"))

    for s in _insert("pincodes", "pincode,office_name,state_code,district_area_id,centroid,source_id,is_demo",
                     (f"({q(p.pincode)},{q(p.office_name)},{q(ds.state_code)},{q(p.district_place_id)},{pt(p.lon, p.lat)},"
                      f"{q(p.source_id)},true)" for p in ds.pins)):
        a(s)

    for s in _insert("geology_units", "gid,state_code,lithology_class,formation_name,geom,source_id,is_demo",
                     (f"({u.gid},{q(ds.state_code)},{q(u.class_key)},{q(u.name)},ST_Multi({env(b)}),{q(u.source_id)},true)"
                      for u, b in _units(ds.geology))):
        a(s)
    a(_setval("geology_units", "gid"))
    for s in _insert("soil_units", "gid,state_code,soil_class,soil_name,geom,source_id,is_demo",
                     (f"({u.gid},{q(ds.state_code)},{q(u.class_key)},{q(u.name)},ST_Multi({env(b)}),{q(u.source_id)},true)"
                      for u, b in _units(ds.soil))):
        a(s)
    a(_setval("soil_units", "gid"))
    for s in _insert("aquifer_units", "gid,state_code,aquifer_class,aquifer_name,geom,source_id,is_demo",
                     (f"({u.gid},{q(ds.state_code)},{q(u.class_key)},{q(u.name)},ST_Multi({env(b)}),{q(u.source_id)},true)"
                      for u, b in _units(ds.aquifer))):
        a(s)
    a(_setval("aquifer_units", "gid"))

    res_m = int(round(ds.grid_step * 111_320))
    rows = []
    for gc in ds.cells:
        c = gc.cell
        lat, lon = gc.centroid
        rows.append(f"({c.cell_id},{q(ds.state_code)},{res_m},{env((gc.lon0, gc.lat0, gc.lon1, gc.lat1))},{pt(lon, lat)},"
                    f"{q(c.elevation_m)},{q(c.slope_deg)},{q(c.tpi_m)},{q(c.drainage_density)},{q(c.lineament_density)},"
                    f"{q(c.rainfall_normal_mm)},{q(c.rainfall_cv)},{q(json.dumps(c.source_ids))}::jsonb,true)")
    for s in _insert("feature_grid", "cell_id,state_code,res_m,geom,centroid,elevation_m,slope_deg,tpi_m,drainage_density,"
                                    "lineament_density,rainfall_normal_mm,rainfall_cv,source_ids,is_demo", rows):
        a(s)
    a(_setval("feature_grid", "cell_id"))

    rows = []
    for gc, r in repo.potential_cells(today):
        scores = {f.key: round(f.score, 1) for f in r.factors if f.available and f.score is not None}
        rows.append(f"({gc.cell.cell_id},{q(r.score)},{q(r.klass)},{q(round(r.coverage, 3))},{q(json.dumps(scores))}::jsonb,"
                    f"{q(cfg.method_version)},now(),true)")
    for s in _insert("potential_cells", "cell_id,regional_score,regional_class,coverage,factor_scores,method_version,computed_at,is_demo", rows):
        a(s)

    for s in _insert("rainfall_cells", "cell_key,geom,is_demo",
                     (f"({q(r.key)},{pt(r.lon, r.lat)},true)" for r in ds.rain_cells)):
        a(s)
    for s in _insert("rainfall_annual", "cell_key,year,annual_mm,monsoon_mm,source_id,is_demo",
                     (f"({q(r.key)},{y},{v[0]},{v[1]},'demo_rainfall',true)" for r in ds.rain_cells for y, v in sorted(r.annual.items()))):
        a(s)

    for s in _insert("observation_wells", "well_id,station_code,name,state_code,well_type,agency,geom,source_id,is_demo",
                     (f"({w.well_id},{q(w.station_code)},{q(w.name)},{q(ds.state_code)},'dug_well',{q(w.agency)},{pt(w.lon, w.lat)},"
                      f"{q(w.source_id)},true)" for w in ds.wells)):
        a(s)
    a(_setval("observation_wells", "well_id"))
    for s in _insert("water_level_readings", "well_id,measured_on,season,depth_to_water_m,source_id,is_demo",
                     (f"({w.well_id},{q(r.measured_on)},{q(r.season)},{r.depth_to_water_m},{q(w.source_id)},true)"
                      for w in ds.wells for r in w.readings)):
        a(s)

    for s in _insert("borewell_records", "borewell_id,state_code,geom,location_accuracy_m,drilled_year,depth_ft,yield_lpm,outcome,record_origin,source_id,is_demo",
                     (f"({b.borewell_id},{q(ds.state_code)},{pt(b.lon, b.lat)},{q(b.location_accuracy_m)},{q(b.drilled_year)},"
                      f"{b.depth_ft},{q(b.yield_lpm)},{q(b.outcome)},'DEMO',{q(b.source_id)},true)" for b in ds.borewells)):
        a(s)
    a(_setval("borewell_records", "borewell_id"))
    for s in _insert("geophysical_surveys", "survey_id,state_code,geom,method,survey_year,weathered_thickness_m,fracture_zone_top_m,"
                                            "fracture_zone_bottom_m,interpreted_suitability,interpretation_note,agency,source_id,is_demo",
                     (f"({v.survey_id},{q(ds.state_code)},{pt(v.lon, v.lat)},{q(v.method)},{q(v.survey_year)},{q(v.weathered_thickness_m)},"
                      f"{q(v.fracture_zone_top_m)},{q(v.fracture_zone_bottom_m)},{q(v.suitability)},{q(v.note)},'DEMO',{q(v.source_id)},true)"
                      for v in ds.ves)):
        a(s)
    a(_setval("geophysical_surveys", "survey_id"))

    a("COMMIT;")
    a("ANALYZE;")
    return "\n".join(L) + "\n"
