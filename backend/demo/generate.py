def build_demo_dataset(seed: int = 20260630, cfg: StateConfig | None = None) -> Dataset:
    cfg = cfg or load_state_config("telangana")
    rng = np.random.default_rng(seed)
    ds = Dataset(is_demo=True, anchor_date=ANCHOR, state_code=cfg.code, state_en=cfg.name["en"],
                 state_te=cfg.name["te"], coverage_bbox=(LON0, LAT0, LON1, LAT1), sources=_demo_sources())

    # ---- terrain fields on the feature grid ------------------------------------------------
    ncols = int(round((LON1 - LON0) / STEP))
    nrows = int(round((LAT1 - LAT0) / STEP))
    ds.grid_origin, ds.grid_step, ds.grid_shape = (LON0, LAT0), STEP, (nrows, ncols)
    lon_c = LON0 + (np.arange(ncols) + 0.5) * STEP
    lat_c = LAT0 + (np.arange(nrows) + 0.5) * STEP
    LON, LAT = np.meshgrid(lon_c, lat_c)
    X, Y = _xy(LON, LAT)
    Lx, Ly = float(X.max()), float(Y.max())

    f_long, f_short = _field(rng, (35, 70)), _field(rng, (6, 14))
    f_s, f_d, f_l = _field(rng, (5, 12)), _field(rng, (8, 25)), _field(rng, (6, 18))
    f_r, f_cv = _field(rng, (30, 80)), _field(rng, (20, 60))

    hills = [(rng.uniform(0, Lx), rng.uniform(0, Ly), rng.uniform(1.8, 4.0), rng.uniform(50, 140)) for _ in range(22)]
    hill = np.zeros_like(X)
    for hx, hy, sg, amp in hills:
        hill += amp * np.exp(-((X - hx) ** 2 + (Y - hy) ** 2) / (2 * sg ** 2))

    def river1(x): return 0.38 * Ly + 9 * np.sin(2 * np.pi * x / 55 + 0.7) + 0.05 * (x - Lx / 2)
    def river2(x): return 0.80 * Ly + 6 * np.sin(2 * np.pi * x / 40 + 2.0)

    dist_r1, dist_r2 = np.abs(Y - river1(X)), np.abs(Y - river2(X))
    valley = 28 * np.exp(-(dist_r1 / 3.0) ** 2) + 18 * np.exp(-(dist_r2 / 2.5) ** 2)
    elevation = 530 + 35 * f_long(X, Y) + 12 * f_short(X, Y) + hill - valley
    tpi = elevation - _box_mean(elevation, 2)
    slope = np.clip(0.5 + 0.9 * np.abs(f_s(X, Y)) + 0.16 * hill, 0.2, 25.0)

    dykes = [((0.10 * Lx, 0.15 * Ly), math.radians(35)), ((0.30 * Lx, 0.95 * Ly), math.radians(-40))]

    def dyke_dist(x, y):
        d = np.full_like(np.asarray(x, dtype=float), 1e9)
        for (px, py), th in dykes:
            ux, uy = math.cos(th), math.sin(th)
            d = np.minimum(d, np.abs((x - px) * uy - (y - py) * ux))
        return d

    drain = np.clip(1.5 + 0.6 * f_d(X, Y) + 0.2 * slope, 0.4, 6.0)
    lineam = np.clip(0.9 + 0.55 * f_l(X, Y) + 0.9 * np.exp(-(dyke_dist(X, Y) / 2.0) ** 2), 0.0, 2.8)
    rain_norm = np.clip(790 + 55 * f_r(X, Y) + 110 * (Y / Ly - 0.5), 600, 1000)
    rain_cv = np.clip(26 + 4 * f_cv(X, Y), 18, 38)

    src_ids = {"slope": "demo_terrain", "topographic_position": "demo_terrain",
               "drainage_density": "demo_drainage", "lineament_density": "demo_lineament", "rainfall": "demo_rainfall"}
    cid = 0
    for i in range(nrows):
        for j in range(ncols):
            cid += 1
            fc = FeatureCell(cell_id=cid, elevation_m=round(float(elevation[i, j]), 1), slope_deg=round(float(slope[i, j]), 2),
                             tpi_m=round(float(tpi[i, j]), 1), drainage_density=round(float(drain[i, j]), 2),
                             lineament_density=round(float(lineam[i, j]), 2),
                             rainfall_normal_mm=round(float(rain_norm[i, j]), 0), rainfall_cv=round(float(rain_cv[i, j]), 1),
                             source_ids=dict(src_ids))
            ds.cells.append(GridCell(fc, LON0 + j * STEP, LAT0 + i * STEP, LON0 + (j + 1) * STEP, LAT0 + (i + 1) * STEP))

    # ---- geology blocks (0.025 deg) --------------------------------------------------------------
    gsize = 0.025
    g_cols, g_rows = int(round((LON1 - LON0) / gsize)), int(round((LAT1 - LAT0) / gsize))
    g_xs, g_ys = LON0 + np.arange(g_cols + 1) * gsize, LAT0 + np.arange(g_rows + 1) * gsize
    seed_pts = [(rng.uniform(0, Lx), rng.uniform(0, Ly)) for _ in range(18)]
    lith_w = {"granite_gneiss": .50, "schist": .10, "quartzite": .06, "basalt": .07, "sandstone": .10,
              "limestone": .07, "shale": .10}
    seed_cls = [_weighted_choice(rng, lith_w) for _ in seed_pts]
    hill_at = lambda x, y: sum(a * math.exp(-((x - hx) ** 2 + (y - hy) ** 2) / (2 * sg ** 2)) for hx, hy, sg, a in hills)  # noqa: E731

    def lith_label(c): return cfg.categorical_label("lithology", c)["en"]
    gid = 0
    geo_class_grid: dict[tuple[int, int], str] = {}
    for gi in range(g_rows):
        for gj in range(g_cols):
            lon0, lat0 = LON0 + gj * gsize, LAT0 + gi * gsize
            cx, cy = _xy(lon0 + gsize / 2, lat0 + gsize / 2)
            cx, cy = float(cx), float(cy)
            k = int(np.argmin([(cx - sx) ** 2 + (cy - sy) ** 2 for sx, sy in seed_pts]))
            cls = seed_cls[k]
            if abs(cy - float(river1(cx))) < 2.0 or abs(cy - float(river2(cx))) < 1.5:
                cls = "alluvium"
            elif float(dyke_dist(cx, cy)) < 1.8 and rng.random() < 0.7:
                cls = "dolerite_dyke"
            elif hill_at(cx, cy) > 70 and rng.random() < 0.6:
                cls = "quartzite"
            gid += 1
            geo_class_grid[(gi, gj)] = cls
            ds.geology.append(PolyUnit(gid, cls, f"{lith_label(cls)} (synthetic block)", _ring(g_xs, g_ys, gi, gj), "demo_geology"))

    def geo_at(lon, lat):
        gj = min(max(int((lon - LON0) // gsize), 0), g_cols - 1)
        gi = min(max(int((lat - LAT0) // gsize), 0), g_rows - 1)
        return geo_class_grid[(gi, gj)]

    # ---- aquifer blocks (0.1 deg) derived from geology ----------------------------------------------
    asize = 0.10
    a_cols, a_rows = int(round((LON1 - LON0) / asize)), int(round((LAT1 - LAT0) / asize))
    a_xs, a_ys = LON0 + np.arange(a_cols + 1) * asize, LAT0 + np.arange(a_rows + 1) * asize
    aq_map = {"alluvium": "alluvial", "sandstone": "consolidated_sedimentary", "limestone": "consolidated_sedimentary",
              "shale": "consolidated_sedimentary", "basalt": "basalt_aquifer", "quartzite": "massive_crystalline",
              "dolerite_dyke": "massive_crystalline"}
    gid = 0
    for ai in range(a_rows):
        for aj in range(a_cols):
            lon0, lat0 = LON0 + aj * asize, LAT0 + ai * asize
            lith = geo_at(lon0 + asize / 2, lat0 + asize / 2)
            cls = aq_map.get(lith) or ("weathered_fractured_crystalline" if rng.random() < 0.72 else "massive_crystalline")
            gid += 1
            label = cfg.categorical_label("aquifer", cls)["en"]
            ds.aquifer.append(PolyUnit(gid, cls, f"{label} (synthetic block)", _ring(a_xs, a_ys, ai, aj), "demo_aquifer"))

    # ---- soil blocks (0.06 deg) ------------------------------------------------------------------------
    ssize = 0.06
    s_cols, s_rows = int(round((LON1 - LON0) / ssize)), int(round((LAT1 - LAT0) / ssize))
    s_xs, s_ys = LON0 + np.arange(s_cols + 1) * ssize, LAT0 + np.arange(s_rows + 1) * ssize
    soil_w = {"red_soil": .35, "black_cotton": .15, "sandy_loam": .15, "loam": .10, "clay_loam": .10,
              "lateritic": .05, "skeletal_rocky": .10}
    soil_seeds = [(rng.uniform(0, Lx), rng.uniform(0, Ly)) for _ in range(12)]
    soil_cls = [_weighted_choice(rng, soil_w) for _ in soil_seeds]
    gid = 0
    for si in range(s_rows):
        for sj in range(s_cols):
            lon0, lat0 = LON0 + sj * ssize, LAT0 + si * ssize
            cx, cy = _xy(lon0 + ssize / 2, lat0 + ssize / 2)
            cx, cy = float(cx), float(cy)
            k = int(np.argmin([(cx - sx) ** 2 + (cy - sy) ** 2 for sx, sy in soil_seeds]))
            cls = soil_cls[k]
            if abs(cy - float(river1(cx))) < 3.0 or abs(cy - float(river2(cx))) < 2.5:
                cls = "loam" if rng.random() < 0.5 else "sandy_loam"
            elif hill_at(cx, cy) > 60:
                cls = "skeletal_rocky"
            gid += 1
            label = cfg.categorical_label("soil", cls)["en"]
            ds.soil.append(PolyUnit(gid, cls, f"{label} (synthetic block)", _ring(s_xs, s_ys, si, sj), "demo_soil"))

    # ---- rainfall series on a 0.25 deg ("IMD-like") grid -----------------------------------------------------
    years = list(range(2010, 2026))
    year_effect = {y: float(rng.normal(0, 1)) for y in years}
    for rlat in np.arange(16.75, 18.51, 0.25):
        for rlon in np.arange(77.50, 79.26, 0.25):
            i = min(max(int((rlat - LAT0) // STEP), 0), nrows - 1)
            j = min(max(int((rlon - LON0) // STEP), 0), ncols - 1)
            normal = float(rain_norm[i, j])
            annual = {}
            for y in years:
                mm = max(0.4 * normal, normal * (1 + 0.16 * year_effect[y] + 0.07 * float(rng.normal())))
                annual[y] = (round(mm, 1), round(mm * 0.8, 1))
            ds.rain_cells.append(RainCell(f"demo025_{rlon:.2f}_{rlat:.2f}", float(rlat), float(rlon), annual))

    # ---- observation wells with seasonal readings --------------------------------------------------------------
    real_wells_file = Path(__file__).resolve().parent / "telangana_nwic_wells.json"
    if not real_wells_file.exists():
        real_wells_file = Path(__file__).resolve().parents[1] / "data" / "telangana_nwic_wells.json"

    if real_wells_file.exists():
        with open(real_wells_file, "r", encoding="utf-8") as f:
            w_data = json.load(f)
        for item in w_data:
            rds = [Reading(date.fromisoformat(r["date"]), r["season"], float(r["depth_to_water_m"])) for r in item.get("readings", [])]
            ds.wells.append(ObservationWell(
                well_id=item["well_id"],
                station_code=item["station_code"],
                lat=float(item["lat"]),
                lon=float(item["lon"]),
                readings=rds,
                name=item["name"],
                agency=item.get("agency", "Telangana GW"),
                source_id="nwic_telangana_gw"
            ))
        ds.sources["nwic_telangana_gw"] = SourceRef(
            source_id="nwic_telangana_gw",
            name_en="Ground Water Level Telemetry (NWIC/NWDP Telangana)",
            name_te="భూగర్భ జల మట్టాల టెలిమెట్రీ (NWIC/NWDP తెలంగాణ)",
            publisher="National Water Informatics Centre (NWIC) & Telangana Ground Water Department",
            layer_kind="water_level",
            url="https://nwdp.nwic.gov.in/dataset/ground-water-level-telemetry-daily-telangana-gw/resource/ce37832e-2783-423f-90e2-ab40eaa32ed1",
            license="Government Open Data Licence - India (GODL)",
            data_last_updated=date(2026, 11, 20),
            is_demo=False
        )
    else:
        f_w = _field(rng, (10, 30))
        wells_xy: list[tuple[float, float]] = []
        tries = 0
        while len(wells_xy) < 130 and tries < 8000:
            tries += 1
            lon = rng.uniform(LON0 + 0.03, LON1 - 0.03)
            lat = rng.uniform(LAT0 + 0.03, LAT1 - 0.03)
            x, y = (float(v) for v in _xy(lon, lat))
            if all(math.hypot(x - a, y - b) >= 6.0 for a, b in wells_xy):
                wells_xy.append((x, y))
                lon_lat = (lon, lat)
                i = min(int((lat - LAT0) // STEP), nrows - 1)
                j = min(int((lon - LON0) // STEP), ncols - 1)
                base = float(np.clip(11 + 0.45 * tpi[i, j] + 4 * float(f_w(np.array(x), np.array(y))) + rng.normal(0, 2), 2.5, 48))
                trend = float(np.clip(rng.normal(0.12, 0.25), -0.3, 0.9))
                n = len(wells_xy)
                readings = []
                for yr in range(2016, 2027):
                    pre = max(1.0, base + trend * (yr - 2016) + float(rng.normal(0, 0.9)))
                    readings.append(Reading(date(yr, 5, 15), "pre_monsoon", round(pre, 2)))
                    if yr <= 2025:
                        post = max(0.8, 0.55 * pre + float(rng.normal(0, 0.8)))
                        readings.append(Reading(date(yr, 11, 15), "post_monsoon", round(post, 2)))
                ds.wells.append(ObservationWell(well_id=n, station_code=f"DEMO-OW-{n:03d}", lat=lat, lon=lon,
                                                readings=readings, name=f"Demo observation well {n}", agency="DEMO",
                                                source_id="demo_water_levels"))

    # ---- gazetteer ---------------------------------------------------------------------------------------------------
    pid = 0
    d_ids: dict[str, int] = {}
    for en, te, lat, lon in DISTRICTS:
        pid += 1
        d_ids[en] = pid
        ds.places.append(Place(pid, "district", en, te, lat, lon, None, "demo_admin"))
    m_ids: dict[tuple[str, str], int] = {}
    for en, te, dist, lat, lon in MANDALS:
        pid += 1
        m_ids[(en, dist)] = pid
        ds.places.append(Place(pid, "mandal", en, te, lat, lon, d_ids[dist], "demo_admin"))
    offsets = [(0.035, 0.045), (-0.04, -0.03)]
    for en, te, dist, lat, lon in MANDALS[1:11:2]:                 # a few synthetic villages
        for k, (dlat, dlon) in enumerate(offsets, start=1):
            pid += 1
            ds.places.append(Place(pid, "village", f"Demo Village {en}-{k}", f"నమూనా గ్రామం {te}-{k}",
                                   lat + dlat, lon + dlon, m_ids[(en, dist)], "demo_admin"))
    for code, office, dist, lat, lon in PINS:
        ds.pins.append(Pin(code, office, lat, lon, d_ids.get(dist), "demo_pincode"))

    _add_borewells_and_ves(ds, cfg, rng, wells_xy_fn=_xy)
    return ds


def _add_borewells_and_ves(ds: Dataset, cfg: StateConfig, rng, wells_xy_fn) -> None:
    """Draw borewell outcomes and VES results from a hidden 'truth'.

    truth q = regional index + hidden local field (sd 12) + noise (sd 14). Because the local
    field is NOT visible to the regional index, nearby records carry genuinely new
    information - which is exactly what the local-evidence stage is meant to exploit.
    """
    from app.repository.memory import MemoryRepository

    repo = MemoryRepository(ds, cfg)
    pw = prepare_wells(ds.wells, cfg, ds.anchor_date)
    hidden = _field(rng, (3, 9), n=8)
    yc = cfg.section("evidence")["yield_classes_lpm"]

    def regional_at(lat, lon):
        gc = repo._cell_at(lat, lon)
        if gc is None:
            return None, None
        r = regional_for_point(lat=lat, lon=lon, cell=gc.cell, lithology=repo._geo.lookup(lat, lon),
                               aquifer=repo._aq.lookup(lat, lon), soil=repo._soil.lookup(lat, lon),
                               prepared_wells=pw, cfg=cfg)
        return r.score, summarize_prepared(lat, lon, pw, cfg).pre_idw_m

    def truth(lat, lon, sd):
        score, dtw = regional_at(lat, lon)
        if score is None:
            return None, None
        x, y = (float(v) for v in wells_xy_fn(lon, lat))
        return score + 12 * float(hidden(np.array(x), np.array(y))) + float(rng.normal(0, sd)), dtw

    place_pts = [(p.lat, p.lon) for p in ds.places if LAT0 < p.lat < LAT1 and LON0 < p.lon < LON1]
    bid, attempts = 0, 0
    while bid < 700 and attempts < 5000:
        attempts += 1
        if rng.random() < 0.6 and place_pts:
            plat, plon = place_pts[int(rng.integers(len(place_pts)))]
            lat, lon = plat + float(rng.normal(0, 0.03)), plon + float(rng.normal(0, 0.035))
        else:
            lat, lon = rng.uniform(LAT0, LAT1), rng.uniform(LON0, LON1)
        if not (LAT0 < lat < LAT1 and LON0 < lon < LON1):
            continue
        q, dtw = truth(lat, lon, 14.0)
        if q is None:
            continue
        dtw = 15.0 if dtw is None else dtw
        dry = rng.random() < 1.0 / (1.0 + math.exp((q - 45.0) / 9.0))
        if dry:
            yld, outcome = 0.0, "dry"
            depth = float(np.clip(rng.normal(400 + 5 * dtw, 90), 200, 800))
        else:
            median = 10 + 2.4 * max(q - 25, 0)
            yld = float(np.clip(math.exp(rng.normal(math.log(median), 0.6)), 3, 600))
            outcome = "low" if yld < yc["low_max"] else ("moderate" if yld < yc["moderate_max"] else "good")
            depth = float(np.clip(rng.normal(250 + 7 * dtw, 55), 120, 700))
        bid += 1
        year = max(2003, 2025 - int(rng.exponential(7)))
        acc = rng.choice([10, 30, 100, 300, 1000, -1], p=[.25, .25, .20, .15, .10, .05])
        ds.borewells.append(BorewellRecord(
            borewell_id=bid, lat=float(lat), lon=float(lon), depth_ft=round(depth / 5) * 5.0, outcome=outcome,
            yield_lpm=round(yld, 1), drilled_year=int(year), location_accuracy_m=None if acc < 0 else int(acc),
            source_id="demo_borewells"))

    n_ves = 0
    while n_ves < 30 and ds.borewells:
        b = ds.borewells[int(rng.integers(len(ds.borewells)))]
        ang, dist_km = rng.uniform(0, 2 * math.pi), rng.uniform(0.3, 1.5)
        lat, lon = b.lat + dist_km * math.sin(ang) / KM_LAT, b.lon + dist_km * math.cos(ang) / KM_LON
        if not (LAT0 < lat < LAT1 and LON0 < lon < LON1):
            continue
        q, _ = truth(lat, lon, 8.0)
        if q is None:
            continue
        suit = "good" if q > 62 else ("moderate" if q > 42 else "poor")
        if rng.random() < 0.12:
            suit = str(rng.choice([s for s in ("good", "moderate", "poor") if s != suit]))
        top = round(float(rng.uniform(22, 62)), 1)
        n_ves += 1
        ds.ves.append(VesSurvey(
            survey_id=n_ves, lat=float(lat), lon=float(lon), method="VES-Schlumberger (synthetic)",
            suitability=suit, survey_year=int(rng.integers(2008, 2025)),
            weathered_thickness_m=round(float(rng.uniform(4, 18)), 1),
            fracture_zone_top_m=None if suit == "poor" else top,
            fracture_zone_bottom_m=None if suit == "poor" else round(top + float(rng.uniform(8, 30)), 1),
            note="DEMO interpretation - synthetic", source_id="demo_ves"))
