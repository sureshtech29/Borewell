# ----------------------------------------------------------------------------- helpers
def _field(rng, wavelengths, n=6):
    """Smooth zero-mean, unit-variance random field as a callable f(X_km, Y_km)."""
    waves = [(2 * np.pi / rng.uniform(*wavelengths), rng.uniform(0, 2 * np.pi), rng.uniform(0, 2 * np.pi))
             for _ in range(n)]

    def f(X, Y):
        out = np.zeros_like(np.asarray(X, dtype=float))
        for k, th, ph in waves:
            out = out + np.cos(k * (X * math.cos(th) + Y * math.sin(th)) + ph)
        return out / math.sqrt(n / 2.0)
    return f


def _box_mean(a: np.ndarray, r: int = 2) -> np.ndarray:
    p = np.pad(a, r, mode="edge")
    out = np.zeros_like(a, dtype=float)
    for dy in range(-r, r + 1):
        for dx in range(-r, r + 1):
            out += p[r + dy:r + dy + a.shape[0], r + dx:r + dx + a.shape[1]]
    return out / (2 * r + 1) ** 2


def _xy(lon, lat):
    return (np.asarray(lon) - LON0) * KM_LON, (np.asarray(lat) - LAT0) * KM_LAT


def _ring(xs, ys, i, j):
    """Closed ring of lattice cell (row i, col j); neighbours share EXACT corner coordinates."""
    x0, x1, y0, y1 = float(xs[j]), float(xs[j + 1]), float(ys[i]), float(ys[i + 1])
    return [(x0, y0), (x1, y0), (x1, y1), (x0, y1), (x0, y0)]


